#!/usr/bin/env bash
# Builds /opt/kape/.env on the EC2 instance from:
#   1. infra/env.production            (non-secret settings, committed)
#   2. SSM Parameter Store /kape-lumen/env/*   (secrets, SecureString, read with the instance role)
#   3. the instance's public IP         (SITE_ADDRESS, e.g. 13-250-1-2.sslip.io)
# The file is root-only (chmod 600) and is never committed. The Gemini key is NOT written here:
# brew-gateway reads it from SSM itself at runtime.
set -euo pipefail

APP_DIR="$(cd "$(dirname "$0")/.." && pwd)"
OUT=/opt/kape/.env
REGION=$(grep -E '^AWS_REGION=' "$APP_DIR/infra/env.production" | cut -d= -f2)

tmp=$(mktemp)
chmod 600 "$tmp"
{
  echo "# Generated by infra/render-env.sh on $(date -u +%FT%TZ). Do not edit; do not copy off this server."
  grep -vE '^\s*(#|$)' "$APP_DIR/infra/env.production"

  # Secrets: /kape-lumen/env/NAME -> NAME=value
  aws ssm get-parameters-by-path --region "$REGION" --path /kape-lumen/env/ --with-decryption \
    --query 'Parameters[].[Name,Value]' --output text |
    while IFS=$'\t' read -r name value; do echo "${name##*/}=${value}"; done

  # Public hostname: an explicit /kape-lumen/env/SITE_ADDRESS (above) wins; otherwise use sslip.io.
  if ! aws ssm get-parameter --region "$REGION" --name /kape-lumen/env/SITE_ADDRESS >/dev/null 2>&1; then
    token=$(curl -sS -X PUT http://169.254.169.254/latest/api/token -H 'X-aws-ec2-metadata-token-ttl-seconds: 60')
    ip=$(curl -sS -H "X-aws-ec2-metadata-token: $token" http://169.254.169.254/latest/meta-data/public-ipv4)
    echo "SITE_ADDRESS=${ip//./-}.sslip.io"
  fi
} > "$tmp"

# Fail loudly if a required value is missing, rather than starting a half-configured app.
for required in GATEWAY_TOKEN MONGO_PASSWORD CREDS_KEY CREDS_IV JWT_SECRET JWT_REFRESH_SECRET CONTENT_BUCKET SITE_ADDRESS; do
  grep -q "^${required}=." "$tmp" || { echo "render-env: missing $required (check SSM /kape-lumen/env/$required)" >&2; rm -f "$tmp"; exit 1; }
done

install -d -m 700 /opt/kape
mv "$tmp" "$OUT"
chmod 600 "$OUT"
echo "render-env: wrote $OUT ($(grep -c '=' "$OUT") settings; SITE_ADDRESS=$(grep '^SITE_ADDRESS=' "$OUT" | cut -d= -f2))"
